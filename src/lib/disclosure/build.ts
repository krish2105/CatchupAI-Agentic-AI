/**
 * AI-use disclosure for academic integrity: a plain record the student can attach to coursework, listing which
 * answers and plans the AI drafted, the pages it cited and what the student approved. Built only from stored
 * records; pure (the data is loaded by disclosure/service.ts), so the same content feeds the page and the file.
 */
export type DisclosureRun = {
  createdAt: string;
  question: string;
  model: string | null;
  facts: { statement: string; sources: { filename: string; page: number }[] }[];
  suggestions: string[];
  offTopic: boolean;
};
export type DisclosurePlan = { createdAt: string; origin: "copilot" | "check-in" | "student"; scenario: string; status: string; decidedAt: string | null };
export type DisclosureInput = {
  generatedAt: string;
  timezone: string;
  runs: DisclosureRun[];
  plans: DisclosurePlan[];
  memories: { text: string; createdAt: string }[];
};

export const ORIGIN_LABEL: Record<DisclosurePlan["origin"], string> = {
  copilot: "the copilot (AI)",
  "check-in": "the daily check-in (no AI model)",
  student: "the student, in the Recovery lab",
};

export function outcomeLabel(status: string, decidedAt: string | null, when: (iso: string) => string): string {
  if (status === "approved") return `Approved by the student${decidedAt ? ` on ${when(decidedAt)}` : ""}`;
  if (status === "rejected") return `Dismissed by the student${decidedAt ? ` on ${when(decidedAt)}` : ""}`;
  if (status === "pending") return "Waiting for the student's decision";
  return "Expired without a decision";
}

const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();

export function buildDisclosure(input: DisclosureInput): string {
  const when = (iso: string) => new Intl.DateTimeFormat("en-GB", { dateStyle: "medium", timeStyle: "short", timeZone: input.timezone }).format(new Date(iso));
  const aiPlans = input.plans.filter((p) => p.origin !== "student");
  const lines: string[] = [
    "# AI-use disclosure",
    "",
    `Generated by CatchUp AI on ${when(input.generatedAt)} (${input.timezone}). It lists where the AI assistant was used for this student's studies, the pages it cited and what the student approved, so it can be attached to coursework.`,
    "",
    "## How AI is used in CatchUp",
    "",
    "- **Copilot answers:** facts must cite a page from the student's own uploaded notes; anything the system couldn't check against that page is removed. Suggestions are advice, not facts.",
    "- **Study plans:** every number is computed by a deterministic planner, not by AI. The copilot and the daily check-in can only draft a plan; it is saved only if the student approves it.",
    "- **Catch-up packs, knowledge checks and Teach-It-Back feedback** are built without AI, from the student's own notes.",
    "",
  ];

  if (!input.runs.length && !aiPlans.length && !input.memories.length) {
    lines.push("No AI use is recorded for this account.", "");
  }

  lines.push(`## Copilot answers (${input.runs.length})`, "");
  input.runs.forEach((run, i) => {
    lines.push(`### ${i + 1}. ${when(run.createdAt)}${run.model ? ` · ${run.model}` : ""}`, "", `**Question:** ${oneLine(run.question)}`, "");
    if (run.offTopic) {
      lines.push("Outside what the copilot helps with; no answer was given.", "");
      return;
    }
    if (run.facts.length) {
      lines.push("**Verified facts, with sources:**", "");
      for (const f of run.facts) lines.push(`- ${oneLine(f.statement)}${f.sources.length ? ` (${f.sources.map((s) => `${s.filename}, p. ${s.page}`).join("; ")})` : ""}`);
      lines.push("");
    }
    if (run.suggestions.length) {
      lines.push("**Suggestions (advice, not facts):**", "");
      for (const s of run.suggestions) lines.push(`- ${oneLine(s)}`);
      lines.push("");
    }
    if (!run.facts.length && !run.suggestions.length) lines.push("No answer was kept for this question.", "");
  });

  lines.push(`## Study plans drafted (${input.plans.length})`, "");
  if (input.plans.length) {
    lines.push("| Drafted | By | Route | Outcome |", "| --- | --- | --- | --- |");
    for (const p of input.plans) lines.push(`| ${when(p.createdAt)} | ${ORIGIN_LABEL[p.origin]} | ${p.scenario} | ${outcomeLabel(p.status, p.decidedAt, when)} |`);
    lines.push("");
  } else lines.push("None.", "");

  lines.push(`## Notes the copilot suggested and the student kept (${input.memories.length})`, "");
  if (input.memories.length) for (const m of input.memories) lines.push(`- ${oneLine(m.text)} (${when(m.createdAt)})`);
  else lines.push("None.");
  lines.push("");
  return lines.join("\n");
}
